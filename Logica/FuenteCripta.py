"""Contrato que el modelo exige a quien le entrega los datos de la cripta.

El juego no sabe si esos datos vienen de la red, del disco (--offline) o de una caché: solo conoce esta lista de
operaciones (§6). Los adaptadores la cumplen sin necesidad de heredar nada de aquí."""
from __future__ import annotations
from typing import Protocol

from DTO.ActorDTO import EnemigoDTO, JugadorDTO
from DTO.MapaDTO import MapaDTO
from DTO.SalaDTO import SalaDTO


class FuenteCripta(Protocol):
    def listar_criptas(self) -> list[str]: ...

    def obtener_id_cripta(self, posicion: int) -> str: ...

    def existe_cripta(self, cripta_id: str) -> bool: ...

    def crear_jugador(self, cripta_id: str) -> JugadorDTO: ...

    def obtener_sala_salida(self, cripta_id: str) -> int: ...

    def total_salas(self, cripta_id: str) -> int: ...

    def construir_sala(self, cripta_id: str, numero_sala: int) -> SalaDTO: ...

    def obtener_mapa(self, cripta_id: str) -> MapaDTO: ...

    def objetos_que_suelta(self, enemigo: EnemigoDTO) -> list: ...

    def precargar_vecinas(self, cripta_id: str, sala_actual: int, profundidad: int | None = None, *args, **kwargs): ...

    def version_cripta(self, cripta_id: str) -> str | None: ...

    def version_catalogo(self) -> str | None: ...

    def reporte(self, cripta_id: str) -> object: ...

    def fijar_fichas_en_uso(self, ids_catalogo: list[str]) -> None: ...
